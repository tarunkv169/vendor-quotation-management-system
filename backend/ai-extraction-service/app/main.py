"""FastAPI application factory (API process).

Run:  uvicorn app.main:app --host 0.0.0.0 --port 8090
Docs: http://localhost:8090/docs  (OpenAPI generated by FastAPI)

`lifespan` builds shared components once at startup and closes them at shutdown.
Extraction jobs run as background tasks inside this process.
"""
from __future__ import annotations

import logging
import re
import uuid
from collections.abc import AsyncIterator
from contextlib import asynccontextmanager

from fastapi import FastAPI, Request
from prometheus_client import make_asgi_app

from app.api.v1 import extraction_routes, health_routes
from app.config.logging_config import configure_logging, correlation_id_var, request_id_var
from app.config.settings import get_settings
from app.container import build_container
from app.exceptions.handlers import register_exception_handlers

log = logging.getLogger(__name__)
_SAFE_ID = re.compile(r"^[A-Za-z0-9-]{1,64}$")


@asynccontextmanager
async def lifespan(app: FastAPI) -> AsyncIterator[None]:
    settings = get_settings()
    configure_logging(settings.log_level, settings.app_name)
    container = build_container(settings)
    app.state.container = container
    log.info("API started (environment=%s)", settings.environment)
    try:
        yield
    finally:
        await container.close()


def create_app() -> FastAPI:
    app = FastAPI(
        title="VQMS AI Extraction Service",
        version="1.0.0",
        description="Extracts structured quotation data from PDF, scanned PDF, image and Excel documents.",
        lifespan=lifespan,
    )

    @app.middleware("http")
    async def correlation_middleware(request: Request, call_next):
        """Propagates X-Correlation-Id (validated) and assigns a request id."""
        incoming = request.headers.get("X-Correlation-Id", "")
        correlation_id = incoming if _SAFE_ID.match(incoming) else str(uuid.uuid4())
        request_id = str(uuid.uuid4())
        tokens = (correlation_id_var.set(correlation_id), request_id_var.set(request_id))
        try:
            response = await call_next(request)
        finally:
            correlation_id_var.reset(tokens[0])
            request_id_var.reset(tokens[1])
        response.headers["X-Correlation-Id"] = correlation_id
        response.headers["X-Request-Id"] = request_id
        return response

    register_exception_handlers(app)
    app.include_router(health_routes.router)
    app.include_router(extraction_routes.router)
    # Scrape endpoint; restrict to the internal network at the ingress/gateway.
    app.mount("/metrics", make_asgi_app())
    return app


app = create_app()
